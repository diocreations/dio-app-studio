import type { VerticalId } from './types'

/**
 * One design system per trade. The palette, type pairing, corner language,
 * layout archetype and navigation style all change — so a salon build and a
 * garage build are visibly different products, not the same page re-labelled.
 */

export type Layout = 'editorial' | 'grid' | 'rows' | 'stack'
export type NavStyle = 'bar' | 'floating' | 'dock'
/** The shell is the app around the content: which tabs exist, what the header
 *  carries, and how an item opens. Trades that share a shell still differ in
 *  theme, but the shell is what stops them reading as one product. */
export type ShellId = 'standard' | 'menu' | 'session' | 'care' | 'listing'
export type AccentStyle = 'solid' | 'block' | 'underline'

export type Theme = {
  layout: Layout
  nav: NavStyle
  dark: boolean
  bg: string
  surface: string
  surface2: string
  ink: string
  muted: string
  line: string
  display: string
  body: string
  /** Numerals: a serif price reads different from a mono one. */
  priceFont: 'display' | 'mono' | 'body'
  weight: number
  tracking: string
  radius: number
  shell?: ShellId
  accentStyle: AccentStyle
  /** The abstract motif used where a photo would go. */
  motif: 'circle' | 'arches' | 'stripes' | 'grid' | 'letter' | 'rings'
}

