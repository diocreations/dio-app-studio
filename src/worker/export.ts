/*
 * Packaging. A store binary needs a signing key, an Apple/Google account and a
 * review queue, so what we generate here is everything up to that line: a
 * complete installable PWA, plus the native wrapper projects with the commands
 * an operator runs (or a CI job runs) to produce the .aab / .ipa.
 */

export type ZipEntry = { name: string; data: Uint8Array }

const encoder = new TextEncoder()

let table: Uint32Array | null = null

function crcTable(): Uint32Array {
  if (table) return table
  const built = new Uint32Array(256)
  for (let index = 0; index < 256; index++) {
    let value = index
    for (let bit = 0; bit < 8; bit++)
      value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1
    built[index] = value >>> 0
  }
  table = built
  return built
}

function crc32(data: Uint8Array): number {
  const lookup = crcTable()
  let crc = 0xffffffff
  for (let index = 0; index < data.length; index++)
    crc = lookup[(crc ^ data[index]) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

function dosTime(date: Date): { time: number; day: number } {
  const time =
    (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2)
  const day =
    ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate()
  return { time, day }
}

/** Store-only ZIP writer: no compression to depend on, valid everywhere. */
export function createZip(entries: ZipEntry[]): Uint8Array {
  const now = new Date()
  const { time, day } = dosTime(now)
  const chunks: number[] = []
  const central: number[] = []

  const push16 = (list: number[], value: number) => {
    list.push(value & 0xff, (value >>> 8) & 0xff)
  }
  const push32 = (list: number[], value: number) => {
    list.push(value & 0xff, (value >>> 8) & 0xff, (value >>> 16) & 0xff, (value >>> 24) & 0xff)
  }

  for (const entry of entries) {
    const name = encoder.encode(entry.name)
    const crc = crc32(entry.data)
    const offset = chunks.length
    push32(chunks, 0x04034b50)
    push16(chunks, 20)
    push16(chunks, 0x0800)
    push16(chunks, 0)
    push16(chunks, time)
    push16(chunks, day)
    push32(chunks, crc)
    push32(chunks, entry.data.length)
    push32(chunks, entry.data.length)
    push16(chunks, name.length)
    push16(chunks, 0)
    for (const byte of name) chunks.push(byte)
    for (const byte of entry.data) chunks.push(byte)

    push32(central, 0x02014b50)
    push16(central, 20)
    push16(central, 20)
    push16(central, 0x0800)
    push16(central, 0)
    push16(central, time)
    push16(central, day)
    push32(central, crc)
    push32(central, entry.data.length)
    push32(central, entry.data.length)
    push16(central, name.length)
    push16(central, 0)
    push16(central, 0)
    push16(central, 0)
    push16(central, 0)
    push32(central, 0)
    push32(central, offset)
    for (const byte of name) central.push(byte)
  }

  const out: number[] = chunks.slice()
  const centralOffset = out.length
  for (const byte of central) out.push(byte)
  push32(out, 0x06054b50)
  push16(out, 0)
  push16(out, 0)
  push16(out, entries.length)
  push16(out, entries.length)
  push32(out, central.length)
  push32(out, centralOffset)
  push16(out, 0)
  return new Uint8Array(out)
}

function text(name: string, content: string): ZipEntry {
  return { name, data: encoder.encode(content) }
}

function projectName(project: Project): string {
  return project.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .slice(0, 40) || 'restaurant-app'
}

function header(project: Project, what: string): string {
  return `${project.name} — ${what}
Generated by Plattr · build v${project.version} · ${new Date().toISOString().slice(0, 10)}

Every screen, price and section here comes from the approved build spec.
If the customer asks for a change, edit the project in Plattr and download a
fresh package; the exported files are snapshots, not a live link.
`
}

export function pwaBundle(project: Project): Uint8Array {
  const spec: AppSpec = project.spec
  return createZip([
    text(
      'index.html',
      renderApp(spec, {
        token: project.token,
        version: project.version,
        slot: project.variationSlot ?? undefined,
        doc: project.doc ?? undefined,
      }),
    ),
    text('manifest.webmanifest', renderManifest(spec)),
    text('sw.js', renderServiceWorker(project.version)),
    text('icon.svg', renderIcon(spec)),
    text(
      'README.txt',
      `${header(project, 'installable web app')}
Contents
--------
index.html               The whole app in one file.
manifest.webmanifest     Install metadata (name, colours, icon).
sw.js                    Service worker: offline shell.
icon.svg                 App icon.

Host it anywhere static (Cloudflare Pages, Netlify, S3, your own nginx) with
HTTPS. Opening index.html over https on a phone shows "Add to Home Screen".

Hosting tip: serve index.html for any path so deep links keep working.

Check before handover
---------------------
1. Phone -> open the URL -> Add to Home Screen.
2. Turn on airplane mode and reopen: the app should still boot.
3. Place a test order and a test booking.
`,
    ),
  ])
}

export function androidBundle(project: Project): Uint8Array {
  const spec = project.spec
  const slug = projectName(project)
  const manifest = {
    packageId: `com.plattr.${slug.replace(/-/g, '')}`,
    host: 'app.example.com',
    name: spec.name,
    launcherName: spec.name.slice(0, 24),
    display: 'standalone',
    themeColor: spec.accent,
    backgroundColor: '#fbf7f1',
    startUrl: '/',
    iconUrl: 'https://app.example.com/icon.svg',
    maskableIconUrl: 'https://app.example.com/icon.svg',
    webManifestUrl: 'https://app.example.com/manifest.webmanifest',
    orientation: 'portrait',
    signingKey: { path: './android.keystore', alias: 'android' },
    appVersionName: `1.0.${project.version}`,
    appVersionCode: project.version,
    enableNotifications: false,
    shortcuts: [],
  }

  return createZip([
    text('twa-manifest.json', JSON.stringify(manifest, null, 2)),
    text(
      'build.sh',
      `#!/usr/bin/env bash
# ${spec.name} — Android package (Trusted Web Activity)
# Produces app-release-bundle.aab for Google Play, or app-release-signed.apk.
set -euo pipefail

# 1. Host the PWA bundle on the domain in twa-manifest.json (HTTPS required).
# 2. Create an upload key if you have none:
#    keytool -genkey -v -keystore android.keystore -alias android \\
#      -keyalg RSA -keysize 2048 -validity 10000

bubblewrap init --manifest=https://app.example.com/manifest.webmanifest
bubblewrap build --skipPwaValidation

# bubblewrap asks for the package id (com.plattr.${slug.replace(/-/g, '')}),
# the keystore and the key alias. Keep the keystore in a password manager:
# losing it means you cannot update the listing again without Play support.

echo "Output: app-release-bundle.aab (Play) / app-release-signed.apk (sideload)"
`,
    ),
    text('assetlinks.json', JSON.stringify(
      [
        {
          relation: ['delegate_permission/common.handle_all_urls'],
          target: {
            namespace: 'android_app',
            package_name: manifest.packageId,
            sha256_cert_fingerprints: ['REPLACE_WITH_UPLOAD_KEY_SHA256'],
          },
        },
      ],
      null,
      2,
    )),
    text(
      'README.txt',
      `${header(project, 'Android package')}
Why this is a project and not an .apk
-------------------------------------
An installable Android binary has to be signed with an upload key that only you
control, and a Play listing needs the app's real package id and developer
account. Handing out a pre-signed APK would put your signing key in a download.

What to run (10–15 minutes, once per customer)
----------------------------------------------
1. Deploy the PWA bundle from the web-app download to the domain in
   twa-manifest.json (HTTPS, valid certificate).
2. Put assetlinks.json at https://<that domain>/.well-known/assetlinks.json
   with the SHA-256 fingerprint of your upload key.
3. bunx @bubblewrap/cli init --manifest=https://<domain>/manifest.webmanifest
4. bubblewrap build
   -> app-release-bundle.aab  (upload to Play Console)
   -> app-release-signed.apk  (direct install / WhatsApp to the owner)

Google Play review is typically 1–5 days for a new account. A new developer
account also needs 12 closed testers for 14 days before production, so plan the
customer's launch date around that, not around this build.
`,
    ),
  ])
}

export function iosBundle(project: Project): Uint8Array {
  const spec = project.spec
  const slug = projectName(project)
  const config = {
    appId: `com.plattr.${slug.replace(/-/g, '')}`,
    appName: spec.name,
    webDir: 'www',
    bundledWebRuntime: false,
    server: { androidScheme: 'https' },
  }
  return createZip([
    text('capacitor.config.json', JSON.stringify(config, null, 2)),
    text(
      'package.json',
      JSON.stringify(
        {
          name: slug,
          version: `1.0.${project.version}`,
          private: true,
          scripts: {
            sync: 'npx cap sync ios',
            open: 'npx cap open ios',
          },
          dependencies: {
            '@capacitor/core': '^7.0.0',
            '@capacitor/ios': '^7.0.0',
          },
          devDependencies: { '@capacitor/cli': '^7.0.0' },
        },
        null,
        2,
      ),
    ),
    text(
      'www/index.html',
      renderApp(spec, {
        token: project.token,
        version: project.version,
        slot: project.variationSlot ?? undefined,
        doc: project.doc ?? undefined,
      }),
    ),
    text('www/manifest.webmanifest', renderManifest(spec)),
    text('www/icon.svg', renderIcon(spec)),
    text(
      'README.txt',
      `${header(project, 'iOS package')}
Why this needs a Mac (or a cloud Mac) and an Apple account
---------------------------------------------------------
iOS binaries are signed against a certificate tied to an Apple Developer
Programme membership ($99/year). There is no way to hand a restaurant owner a
working IPA without that certificate, and a non-App-Store IPA only installs on
devices registered to the account (ad hoc, 100 devices max) — so TestFlight is
the normal way to show them the app on their own iPhone.

What to run
-----------
1. bun install
2. npx cap add ios
3. npx cap sync ios
4. npx cap open ios      # opens Xcode
5. In Xcode: set the team, bump the bundle id if needed, then
   Product > Archive > Distribute App > App Store Connect.
6. In App Store Connect: add screenshots, a privacy policy URL, and the
   business's contact details.

Review notes for this category
------------------------------
- Guideline 4.2 (minimum functionality): a thin wrapper around a website can be
  rejected. This build has real in-app screens (menu, cart, bookings) so it
  usually passes, but the reviewer must be able to reach every feature without
  a login.
- Guideline 3.1.1: physical goods and in-person services are paid outside the
  app (at the counter or via your PSP). Do not add in-app payment for those.
- First review is typically 24–72 hours; budget a week.
`,
    ),
  ])
}

export function bundleFor(project: Project, kind: string): Uint8Array | null {
  if (kind === 'pwa') return pwaBundle(project)
  if (kind === 'android') return androidBundle(project)
  if (kind === 'ios') return iosBundle(project)
  return null
}

export function bundleFilename(project: Project, kind: string): string {
  return `${projectName(project)}-${kind}-v${project.version}.zip`
}

export function downloadSummary(project: Project): string {
  return `One-time build ${money(project.quote.oneTime)}`
}
